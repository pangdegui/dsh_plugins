/**
 * Regenerate `lib/catalog.js` from a WorkBuddy desktop product-config cache.
 *
 * The desktop app caches its server-issued product configuration under
 * `~/.workbuddy/storage/<user>/scoped/<hash>/wb-product-config.json`; its
 * `product-config-snapshot.data.models` array is the authoritative model list
 * for that install. This script keeps the filter in one place:
 *
 *   - keep models that advertise tool calling (an agent loop needs it) and a
 *     real input window;
 *   - drop image/video/completion routes and internal `codewise-*` helpers,
 *     which `/v2/chat/completions` does not serve as chat models.
 *
 * Usage:
 *   node tools/gen-catalog.mjs [path/to/wb-product-config.json]
 *
 * Without an argument the script prints the path it expected and exits 2.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')

const input = process.argv[2] ?? process.env.WB_PRODUCT_CONFIG
if (input === undefined) {
  console.error('usage: node tools/gen-catalog.mjs <wb-product-config.json>')
  console.error('hint: %USERPROFILE%\\.workbuddy\\storage\\<user>\\scoped\\<hash>\\wb-product-config.json')
  process.exit(2)
}

const snapshot = JSON.parse(fs.readFileSync(input, 'utf8'))
const models = snapshot?.['product-config-snapshot']?.data?.models
if (!Array.isArray(models)) throw new Error(`${input}: product-config-snapshot.data.models is missing`)

const SKIP = new Set(['completion-gf', 'wb-lite', 'codewise-completions', 'codewise-rewrite', 'codewise-jump', 'codewise-nes-a4-027-aide'])
const picked = models.filter((model) => {
  if (SKIP.has(model.id)) return false
  if (model.supportsToolCall !== true) return false
  return Number.isInteger(model.maxInputTokens) && model.maxInputTokens > 0
})

const counts = new Map()
for (const model of picked) counts.set(model.name, (counts.get(model.name) ?? 0) + 1)

const lines = [
  '/**',
  ' * The WorkBuddy model catalog this plugin offers to DSH.',
  ' *',
  ' * Generated by `tools/gen-catalog.mjs` from the desktop app\'s cached',
  ' * product configuration (`product-config-snapshot.data.models`), filtered to',
  ' * models that advertise tool calling and a real input window: the ones that',
  ' * can serve an agent loop over `/v2/chat/completions`. Image, video,',
  ' * completion and internal `codewise-*` routes are intentionally omitted.',
  ' *',
  ' * Keep entries in the app\'s own order: it is the order the product itself',
  ' * presents, and `fast-model` / `balanced-model` / `deep-model` are the',
  ' * branded aliases WorkBuddy\'s own UI defaults to.',
  ' */',
  'export const WORKBUDDY_MODELS = [',
]
for (const model of picked) {
  const name = counts.get(model.name) > 1 ? `${model.name} (${model.id})` : model.name
  const parts = [`id: ${JSON.stringify(model.id)}`, `name: ${JSON.stringify(name)}`, `contextWindow: ${model.maxInputTokens}`]
  if (Number.isInteger(model.maxOutputTokens) && model.maxOutputTokens > 0) parts.push(`maxTokens: ${model.maxOutputTokens}`)
  const input = model.supportsImages ? ['text', 'image'] : ['text']
  parts.push(`input: [${input.map((entry) => JSON.stringify(entry)).join(', ')}]`)
  lines.push(`  { ${parts.join(', ')} },`)
}
lines.push(']', '', '/** The id of the model WorkBuddy\'s own UI ships as the default. */', "export const WORKBUDDY_DEFAULT_MODEL = 'deepseek-v4.1-flash'", '')

fs.writeFileSync(path.join(root, 'lib', 'catalog.js'), lines.join('\n'))
console.log(`wrote lib/catalog.js with ${picked.length} of ${models.length} models`)
